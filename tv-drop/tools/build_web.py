"""Builds the standalone TV Drop web interface: one index.html with the CSS and scripts inlined.

The TV serves the split files (assets/web/index.html, app.css, assistant.js, app.js). This
single file is the same interface for use outside the TV (repository, a file on a computer):
it asks for the TV's code or address and talks to it over the local network.

Usage: python3 tv-drop/tools/build_web.py <output.html>
"""
import os
import re
import sys

WEB = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'web')


def read(name):
    with open(os.path.join(WEB, name), encoding='utf-8') as f:
        return f.read()


def inline_script(code):
    # a literal "</script" inside the code would end the tag early
    return '<script>\n' + code.replace('</script', '<\\/script') + '\n</script>'


def build():
    html = read('index.html')
    html = html.replace('<link rel="stylesheet" href="app.css">', '<style>\n' + read('app.css') + '\n</style>')
    html = html.replace('<script src="assistant.js"></script>',
                        '<script>window.TVDROP_STANDALONE = true;</script>\n' + inline_script(read('assistant.js')))
    html = html.replace('<script src="app.js"></script>', inline_script(read('app.js')))
    html = html.replace('<title>TV Drop</title>',
                        '<title>TV Drop</title>\n<meta name="description" content="TV Drop: controle remoto, transmissão e central multimídia para Android TV / Google TV.">\n'
                        '<!-- Generated by tv-drop/tools/build_web.py from tv-drop/assets/web. Edit those files, not this one. -->')
    leftovers = re.findall(r'<(?:script src|link rel="stylesheet")[^>]*>', html)
    if leftovers:
        raise SystemExit('not inlined: %s' % leftovers)
    return html


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    out = build()
    with open(sys.argv[1], 'w', encoding='utf-8') as f:
        f.write(out)
    print('%s: %d KB' % (sys.argv[1], len(out.encode('utf-8')) // 1024))
